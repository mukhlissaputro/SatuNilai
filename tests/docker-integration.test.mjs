import assert from "node:assert/strict";
import test from "node:test";
import { mkdir, writeFile } from "node:fs/promises";

const base = process.env.TEST_BASE_URL ?? `http://127.0.0.1:${process.env.APP_PORT ?? 3000}`;
const email = process.env.ADMIN_EMAIL;
const password = process.env.ADMIN_PASSWORD;

test("Docker: autentikasi, penilaian, bukti privat, laporan dan finalisasi", async () => {
  assert.ok(email && password, "Set ADMIN_EMAIL dan ADMIN_PASSWORD");
  let cookie = "";
  async function call(path, method = "GET", data, expected = 200) {
    const headers = { origin: base, ...(cookie ? { cookie } : {}) };
    if (data && !(data instanceof FormData)) headers["content-type"] = "application/json";
    const response = await fetch(`${base}${path}`, { method, headers, body: data instanceof FormData ? data : data ? JSON.stringify(data) : undefined });
    assert.equal(response.status, expected, `${method} ${path}: ${await response.clone().text()}`);
    return response;
  }
  await call("/api/health");
  await call("/api/me", "GET", undefined, 401);
  await call("/api/bootstrap", "POST", {}, 403);
  const login = await call("/api/auth/login", "POST", { email, password });
  cookie = login.headers.get("set-cookie").split(";")[0];
  assert.equal((await (await call("/api/me")).json()).user.role, "admin");
  const suffix = Date.now().toString(36);
  const create = async (data) => (await (await call("/api/admin", "POST", data, 201)).json()).id;
  const typeId = await create({ resource: "type", code: `T-${suffix}`, name: "Docker integration" });
  const periodId = await create({ resource: "period", typeId, year: 2026, name: "Docker test", maxScore: 5, startsAt: "2026-01-01", dueAt: "2026-12-31" });
  const admin = await (await call("/api/admin")).json();
  const versionId = admin.periods.find((p) => p.id === periodId).instrumentVersionId;
  const categoryId = await create({ resource: "category", versionId, code: "1", name: "Kategori", weight: 100 });
  const subId = await create({ resource: "subcategory", parentId: categoryId, code: "1.1", name: "Subkategori", target: 5, weight: 100 });
  const indicatorId = await create({ resource: "indicator", parentId: subId, code: "1.1.1", name: "Indikator" });
  const staffEmail = `docker-${suffix}@localhost`;
  await create({ resource: "user", email: staffEmail, name: "Docker Staff", role: "staff", password, assessmentTypeIds: [typeId] });
  const adminCookie = cookie;
  const staffLogin = await call("/api/auth/login", "POST", { email: staffEmail, password });
  cookie = staffLogin.headers.get("set-cookie").split(";")[0];
  const score = await (await call("/api/assessment-workspace", "POST", { periodId, indicatorId, value: 4 })).json();
  const form = new FormData();
  form.set("scoreId", score.scoreId); form.set("title", "Bukti Docker");
  form.set("file", new Blob(["%PDF-1.4\nDocker integration evidence\n%%EOF"], { type: "application/pdf" }), "bukti.pdf");
  const uploaded = await (await call("/api/evidence", "POST", form, 201)).json();
  const download = await call(`/api/evidence/${uploaded.evidence.id}/download`);
  assert.match(await download.text(), /Docker integration evidence/);
  cookie = "";
  await call(`/api/evidence/${uploaded.evidence.id}/download`, "GET", undefined, 401);
  cookie = adminCookie;
  const notificationData = await (await call("/api/notifications")).json();
  assert.ok(notificationData);
  await call("/api/notifications", "PATCH", { key: `docker-${suffix}` });
  await call("/api/assessment-workspace", "PATCH", { action: "review", scoreId: score.scoreId, decision: "approved" });
  await call("/api/assessment-workspace", "PATCH", { action: "finalize", periodId, finalValues: { [subId]: 4.5 } });
  const pdf = await call(`/api/reports/pdf?periodId=${periodId}`);
  assert.match(await pdf.text(), /^%PDF/);
  const excel = await call(`/api/reports/excel?periodId=${periodId}`);
  assert.match(await excel.text(), /Workbook/);
  await call(`/api/dashboard?periodId=${periodId}`);
  await call(`/api/assessment-workspace?periodId=${periodId}`);
  await call(`/api/evidence-repository?periodId=${periodId}`);
  const repositoryForm = new FormData();
  repositoryForm.set("title", `Docker repository ${suffix}`);
  repositoryForm.set("url", "https://example.org/evidence");
  const repositoryEvidence = await (await call("/api/evidence-repository", "POST", repositoryForm, 201)).json();
  await call("/api/evidence-repository", "DELETE", { id: repositoryEvidence.id });
  await mkdir("outputs", { recursive: true });
  await writeFile("outputs/docker-verification.json", JSON.stringify({ typeId, periodId, evidenceId: uploaded.evidence.id, suffix }));
  cookie = staffLogin.headers.get("set-cookie").split(";")[0];
  await call("/api/assessment-workspace", "POST", { periodId, indicatorId, value: 3 }, 409);
  await call("/api/auth/logout", "POST", {});
  await call("/api/me", "GET", undefined, 401);
});
